import kotlin.random.Random

val options = args.toList().chunked(2).associate { it[0] to it[1] }
val random = Random(options["--seed"]?.toInt() ?: 1)
val rounds = options["--rounds"]?.toInt() ?: 15
require(rounds in 1..70)
val output = System.out.bufferedWriter()
fun emit(command: String) { output.appendLine(command) }
val currencies = listOf("KRW", "USD", "XTS", "ZZZ")
for (currency in currencies) {
    emit("OPEN bank_$currency $currency D ANY")
    emit("OPEN debt_$currency $currency C ANY")
    emit("OPEN locked_$currency $currency D NONNEG")
}
emit("OPEN bank_KRW KRW D ANY")
emit("POST manual KRW 2 bank_KRW D 1 debt_KRW C 1")
emit("POST manual KRW 2 bank_KRW D 1 debt_KRW C 1")
emit("POST bad KRW 2 bank_KRW D 0 debt_KRW C 0")
emit("BALANCE absent")
emit("JOURNAL manual")
for (command in listOf("STATUS", "CALL", "QUERY", "COMMIT", "REMOTE")) emit("$command absent")
emit("REFUND invalid absent USD 0")
emit("REFUND missing absent USD 1")
repeat(rounds) { index ->
    val currency = currencies.random(random)
    val other = currencies.first { it != currency }
    val amount = listOf(2L, 100L, 1_000_000_000_000L).random(random)
    val key = if (index % 2 == 0) "order$index" else "Z_rare-$index"
    val pay = "PAY $key bank_$currency debt_$currency $currency $amount"
    emit("PAY invalid$index absent absent $other -1000000000000")
    emit("PAY invalid$index absent absent $other 1")
    emit("PAY invalid$index bank_$currency bank_$currency $other 1")
    emit("PAY invalid$index bank_$currency debt_$other $currency 1")
    emit("PAY invalid$index locked_$currency debt_$currency $currency 1")
    emit("PSP $key TIMEOUT_OK")
    emit(pay)
    emit("REFUND early$index $key $currency 1")
    emit("CALL $key")
    emit("QUERY $key")
    emit(pay)
    emit("STATUS $key")
    emit("CRASH")
    emit("CALL $key")
    emit("COMMIT $key")
    emit(pay)
    emit("PAY $key bank_$currency debt_$currency $other 0")
    emit("REFUND $key absent $other 0")
    emit("CALL $key")
    emit("QUERY $key")
    emit("COMMIT $key")
    emit("REFUND r$index $key $currency $amount")
    emit("REFUND extra$index $key $currency 1")
    emit("REFUND wrong$index r$index $currency 1")
    emit("REFUND wrong$index $key $other 1")
    emit("PSP r$index RETRY")
    emit("CALL r$index")
    emit("COMMIT r$index")
    emit("PSP r$index DECLINE")
    emit("CALL r$index")
    emit("COMMIT r$index")
    emit("REFUND r$index $key $currency $amount")
    emit("REFUND extra$index $key $currency $amount")
    emit("PSP extra$index TIMEOUT_NONE")
    emit("CALL extra$index")
    emit("COMMIT extra$index")
    emit("CALL extra$index")
    emit("QUERY extra$index")
    emit("COMMIT extra$index")
    emit("CALL extra$index")
    emit("PSP extra$index OK")
    emit("CALL extra$index")
    emit("COMMIT extra$index")
    emit("REFUND overflow$index $key $currency 1")
    emit("PAY wait$index bank_$currency debt_$currency $currency 1")
    emit("CALL wait$index")
    emit("QUERY wait$index")
    emit("COMMIT wait$index")
    emit("PSP wait$index DECLINE")
    emit("CALL wait$index")
    emit("CRASH")
    emit("QUERY wait$index")
    emit("COMMIT wait$index")
    for (request in listOf(key, "r$index", "extra$index", "wait$index")) {
        emit("STATUS $request")
        emit("REMOTE $request")
        emit("JOURNAL @$request")
    }
    emit("BALANCE bank_$currency")
    emit("BALANCE debt_$currency")
}
for (currency in currencies) emit("TRIAL $currency")
output.flush()
